#!/usr/bin/env bash
# Sets the GitHub repository slug (owner/repo) everywhere it is baked in:
#   Cargo.toml (repository), AppStream metainfo, AUR PKGBUILD and the AppImage update info.
# The app reads the slug from Cargo.toml at compile time, so no source file needs editing.
#
# Usage: release/set-repo.sh owner/repo
set -euo pipefail

slug="${1:-}"
if [ -z "${slug}" ]; then
    printf 'Usage: %s owner/repo\n' "$0" >&2
    exit 2
fi
if ! printf '%s' "${slug}" | grep -Eq '^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$'; then
    printf 'Error: expected owner/repo, got %s\n' "${slug}" >&2
    exit 2
fi

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
owner="${slug%%/*}"
name="${slug##*/}"
url="https://github.com/${slug}"
changed=0

replace_in() {
    local file="$1" from="$2" to="$3"
    [ -f "${file}" ] || return 0
    [ "${from}" = "${to}" ] && return 0
    if grep -Fq -- "${from}" "${file}"; then
        python3 - "${file}" "${from}" "${to}" <<'PY'
import sys
path, old, new = sys.argv[1:4]
text = open(path, encoding="utf-8").read()
open(path, "w", encoding="utf-8").write(text.replace(old, new))
PY
        printf '  %s: %s -> %s\n' "${file#"${repo_root}"/}" "${from}" "${to}"
        changed=$((changed + 1))
    fi
}

# Discover the slug currently in use, so the script also works the second time.
current="$(sed -n 's|^repository = "https://github.com/\(.*\)"|\1|p' "${repo_root}/Cargo.toml" | head -1)"
[ -n "${current}" ] || current="heronkil777-debug/D-cut"
old_owner="${current%%/*}"
old_name="${current##*/}"
old_url="https://github.com/${current}"

printf 'Repository: %s -> %s\n' "${current}" "${slug}"
replace_in "${repo_root}/Cargo.toml" "repository = \"${old_url}\"" "repository = \"${url}\""
replace_in "${repo_root}/packaging/linux/d-cut.metainfo.xml" "${old_url}" "${url}"
replace_in "${repo_root}/packaging/linux/d-cut.metainfo.xml" "io.github.${old_owner}.Dcut" "io.github.${owner}.Dcut"
replace_in "${repo_root}/release/aur/PKGBUILD" "url=\"${old_url}\"" "url=\"${url}\""
replace_in "${repo_root}/scripts/appimage/assemble.sh" \
    "gh-releases-zsync|${old_owner}|${old_name}|latest|" \
    "gh-releases-zsync|${owner}|${name}|latest|"

if [ "${changed}" -eq 0 ]; then
    printf 'Nothing to change (already %s).\n' "${slug}"
else
    cat <<MSG

Done. Next steps:
  1. Rebuild the AppImage so the embedded update info points to the new repo:
       scripts/build-appimage.sh
  2. Commit the changes (release/aur/.SRCINFO is regenerated by release/prepare-aur.sh).
MSG
fi
